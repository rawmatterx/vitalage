"""Phase 6: does adding accelerometer activity to PhenoAge predict death better?

    .venv-research/bin/python research/fit_model.py

Reads research/data/analysis.csv (from build_dataset.py), writes
research/RESULTS.md and research/combined_params.json.

Model: Gompertz proportional hazards on months since the exam,
    hazard(t) = exp(b0 + b.x + g*t),
fitted by maximum likelihood (scipy). Discrimination is Harrell's C-index.
Ages are converted the way Levine et al. 2018 built PhenoAge: a person's
10-year mortality from a model is mapped to the age that gives the same
10-year mortality in an age-only Gompertz model fitted on the same data.

Validation:
- counts per minute and MVPA exist in both cycles: fit on 2003-04, test on
  2005-06, with a paired bootstrap of the C-index difference on the test set;
- steps exist only in 2005-06: 5-fold cross-validation within 2005-06.
Survey weights and design are ignored (unweighted analysis).
"""

import json
import os
from datetime import date

import numpy as np
import pandas as pd
from scipy.optimize import minimize

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
HORIZON = 120  # months
RNG = np.random.default_rng(2026)
N_BOOT = 300


# ---------------------------------------------------------------- models
def fit_gompertz(X, t, d):
    """Return (beta incl. intercept, gamma) maximising the Gompertz PH likelihood."""
    X1 = np.column_stack([np.ones(len(t)), X])
    mu, sd = X1.mean(0), X1.std(0)
    mu[0], sd[0] = 0.0, 1.0
    Z = (X1 - mu) / sd

    def nll(p):
        b, g = p[:-1], p[-1]
        eta = Z @ b
        if abs(g) < 1e-10:
            H = np.exp(eta) * t
        else:
            H = np.exp(eta) * np.expm1(g * t) / g
        return -(np.sum(d * (eta + g * t)) - np.sum(H))

    p0 = np.zeros(Z.shape[1] + 1)
    p0[0] = np.log(d.sum() / t.sum())
    res = minimize(nll, p0, method="BFGS", options={"gtol": 1e-7, "maxiter": 2000})
    b = res.x[:-1] / sd
    b[0] = res.x[0] - np.sum(res.x[1:-1] * mu[1:] / sd[1:])
    return b, res.x[-1], res


def eta(b, X):
    return b[0] + np.column_stack([X]) @ b[1:]


def mortality_10y(e, g):
    return -np.expm1(-np.exp(e) * np.expm1(g * HORIZON) / g)


def age_equivalent(m, age_model):
    """Age giving 10-year mortality m in the age-only model (Levine's method)."""
    b, g = age_model
    e = np.log(-np.log1p(-m) * g / np.expm1(g * HORIZON))
    return (e - b[0]) / b[1]


# ---------------------------------------------------------------- C-index
def c_index(risk, t, d):
    risk, t, d = map(np.asarray, (risk, t, d))
    conc = ties = total = 0.0
    for i in np.where(d == 1)[0]:
        later = t > t[i]
        n = later.sum()
        if not n:
            continue
        r = risk[later]
        conc += (risk[i] > r).sum()
        ties += (risk[i] == r).sum()
        total += n
    return (conc + 0.5 * ties) / total


def boot_delta(r0, r1, t, d, n=N_BOOT):
    idx = np.arange(len(t))
    deltas = []
    for _ in range(n):
        s = RNG.choice(idx, len(idx))
        deltas.append(c_index(r1[s], t[s], d[s]) - c_index(r0[s], t[s], d[s]))
    return np.percentile(deltas, [2.5, 97.5])


def boot_c(r, t, d, n=N_BOOT):
    idx = np.arange(len(t))
    cs = [c_index(r[s], t[s], d[s]) for s in (RNG.choice(idx, len(idx)) for _ in range(n))]
    return np.percentile(cs, [2.5, 97.5])


# ---------------------------------------------------------------- analysis
def load():
    df = pd.read_csv(os.path.join(DATA, "analysis.csv"))
    df = df[df.permth_exm > 0].copy()
    df["t"] = df.permth_exm.astype(float)
    df["d"] = (df.mortstat == 1).astype(int)
    # PhenoAge acceleration that is uncorrelated with age (residual on age)
    slope, icpt = np.polyfit(df.age, df.phenoage, 1)
    raw = df.phenoage - (icpt + slope * df.age)
    # Winsorize at the 1st/99th percentiles: a few very sick people have
    # PhenoAges far above 100, and a linear hazard in raw acceleration
    # flattens the effect for everyone else.
    lo, hi = np.percentile(raw, [1, 99])
    df["pheno_accel"] = raw.clip(lo, hi)
    df.attrs["accel_fit"] = (float(icpt), float(slope))
    df.attrs["accel_clip"] = (float(lo), float(hi))
    df["log_cpm"] = np.log(df.cpm)
    df["log_mvpa"] = np.log1p(df.mvpa_min_per_day)
    df["log_steps"] = np.log(df.steps_per_day.where(df.steps_per_day > 0))
    df["log_steps_c"] = np.log(df.steps_censored_per_day.clip(lower=500))
    return df


def fmt_ci(c, ci):
    return "%.3f (%.3f to %.3f)" % (c, ci[0], ci[1])


def main():
    df = load()
    lines = []
    out = lines.append
    out("# Phase 6 results: PhenoAge plus accelerometer activity in NHANES 2003-2006")
    out("")
    out("Generated by `research/fit_model.py` on %s. Unweighted analysis of public-use "
        "NHANES 2003-2004 and 2005-2006 with NCHS linked mortality through 31 Dec 2019."
        % date.today().isoformat())
    out("")

    # ---- 1. Reproduce: PhenoAge vs age, all adults with blood data
    t, d = df.t.to_numpy(), df.d.to_numpy()
    b_age, g_age, _ = fit_gompertz(df[["age"]].to_numpy(), t, d)
    b_ph, g_ph, _ = fit_gompertz(df[["phenoage"]].to_numpy(), t, d)
    c_age, c_ph = c_index(df.age.to_numpy(), t, d), c_index(df.phenoage.to_numpy(), t, d)
    out("## 1. Does PhenoAge reproduce?")
    out("")
    out("All adults aged 20-84 with the 9 markers and mortality follow-up: **%d people, "
        "%d deaths**, median follow-up %.1f years." % (len(df), d.sum(), np.median(t) / 12))
    out("")
    out("| Predictor | Hazard ratio per year | C-index (95% CI) |")
    out("|---|---|---|")
    out("| Chronological age | %.3f | %s |" % (np.exp(b_age[1]), fmt_ci(c_age, boot_c(df.age.to_numpy(), t, d))))
    out("| PhenoAge | %.3f | %s |" % (np.exp(b_ph[1]), fmt_ci(c_ph, boot_c(df.phenoage.to_numpy(), t, d))))
    dlt = boot_delta(df.age.to_numpy(), df.phenoage.to_numpy(), t, d)
    out("")
    out("PhenoAge minus age, C-index difference: %+.3f (95%% CI %+.3f to %+.3f)."
        % (c_ph - c_age, dlt[0], dlt[1]))
    out("")

    # ---- 2. Counts per minute and MVPA: train 2003-04, test 2005-06
    act = df.dropna(subset=["cpm"]).copy()
    act = act[act.cpm > 0]
    train, test = act[act.cycle == "2003-2004"], act[act.cycle == "2005-2006"]
    out("## 2. Adding activity counts (fit on 2003-04, tested on 2005-06)")
    out("")
    out("People with >= 4 valid accelerometer days (>= 10 h wear): training %d (%d deaths), "
        "test %d (%d deaths)." % (len(train), train.d.sum(), len(test), test.d.sum()))
    out("")
    out("| Model (fitted on 2003-04) | Test C-index (95% CI) | Change vs PhenoAge (95% CI) |")
    out("|---|---|---|")
    tt, td = test.t.to_numpy(), test.d.to_numpy()
    base_cols = ["age", "pheno_accel"]
    models = {
        "Age only": ["age"],
        "PhenoAge (age + acceleration)": base_cols,
        "PhenoAge + log counts/min": base_cols + ["log_cpm"],
        "PhenoAge + log(1 + MVPA min/day)": base_cols + ["log_mvpa"],
    }
    test_risk, fitted = {}, {}
    for name, cols in models.items():
        b, g, _ = fit_gompertz(train[cols].to_numpy(), train.t.to_numpy(), train.d.to_numpy())
        fitted[name] = (cols, b, g)
        test_risk[name] = eta(b, test[cols].to_numpy())
    ref = test_risk["PhenoAge (age + acceleration)"]
    summary = {}
    for name in models:
        r = test_risk[name]
        c = c_index(r, tt, td)
        ci = boot_c(r, tt, td)
        if name == "PhenoAge (age + acceleration)":
            delta = "reference"
        else:
            dci = boot_delta(ref, r, tt, td)
            delta = "%+.3f (%+.3f to %+.3f)" % (c - c_index(ref, tt, td), dci[0], dci[1])
            summary[name] = (c - c_index(ref, tt, td), dci)
        out("| %s | %s | %s |" % (name, fmt_ci(c, ci), delta))
    out("")
    cols, b, g = fitted["PhenoAge + log counts/min"]
    out("Hazard ratios in the training fit of PhenoAge + log counts/min: per year of age %.3f, "
        "per year of PhenoAge acceleration %.3f, per doubling of counts/min %.3f."
        % (np.exp(b[1]), np.exp(b[2]), np.exp(b[3] * np.log(2))))
    out("")

    # ---- 3. Steps: 5-fold CV within 2005-06
    st = act[act.cycle == "2005-2006"].dropna(subset=["log_steps", "log_steps_c"]).reset_index(drop=True)
    s_t, s_d = st.t.to_numpy(), st.d.to_numpy()
    folds = RNG.permutation(len(st)) % 5

    def cv(cols):
        risk = np.zeros(len(st))
        for k in range(5):
            tr, te = st[folds != k], st[folds == k]
            b, _, _ = fit_gompertz(tr[cols].to_numpy(), tr.t.to_numpy(), tr.d.to_numpy())
            risk[folds == k] = eta(b, te[cols].to_numpy())
        return risk

    risk_base = cv(base_cols)
    out("## 3. Adding daily steps (2005-06 only, 5-fold cross-validation)")
    out("")
    out("%d people (%d deaths). Hip steps per day: raw mean %.0f, censored to minutes with "
        ">= 500 counts mean %.0f (Tudor-Locke et al. 2009 reported 9,676 and 6,540 for "
        "all 2005-06 adults)." % (len(st), s_d.sum(), st.steps_per_day.mean(),
                                  st.steps_censored_per_day.mean()))
    out("")
    out("| Model | Out-of-fold C-index (95% CI) | Change vs PhenoAge (95% CI) |")
    out("|---|---|---|")
    c0 = c_index(risk_base, s_t, s_d)
    out("| PhenoAge (age + acceleration) | %s | reference |" % fmt_ci(c0, boot_c(risk_base, s_t, s_d)))
    for label, col in [("PhenoAge + log censored steps", "log_steps_c"),
                       ("PhenoAge + log raw steps", "log_steps")]:
        r = cv(base_cols + [col])
        c1 = c_index(r, s_t, s_d)
        dci = boot_delta(risk_base, r, s_t, s_d)
        out("| %s | %s | %+.3f (%+.3f to %+.3f) |"
            % (label, fmt_ci(c1, boot_c(r, s_t, s_d)), c1 - c0, dci[0], dci[1]))
        summary[label + " (CV)"] = (c1 - c0, dci)
    out("")

    # Reverse-causation check: drop deaths in the first 2 years
    late = st[~((st.d == 1) & (st.t < 24))].reset_index(drop=True)
    b_all, _, _ = fit_gompertz(st[base_cols + ["log_steps_c"]].to_numpy(), s_t, s_d)
    b_late, _, _ = fit_gompertz(late[base_cols + ["log_steps_c"]].to_numpy(),
                                late.t.to_numpy(), late.d.to_numpy())
    out("Hazard ratio per doubling of censored steps (beyond age and PhenoAge acceleration): "
        "%.3f with all deaths, %.3f after dropping %d deaths in the first 2 years, a check "
        "for ill people moving less." % (np.exp(b_all[3] * np.log(2)), np.exp(b_late[3] * np.log(2)),
                                         len(st) - len(late)))
    out("")

    # ---- Verdict
    primary = "PhenoAge + log censored steps (CV)"
    ship = summary[primary][1][0] > 0
    improved = sorted(k for k, v in summary.items() if v[1][0] > 0)
    out("## Preliminary verdict (superseded by section 4)")
    out("")
    out("Activity measures whose held-out C-index change has a 95%% CI above zero: %s."
        % (", ".join(improved) if improved else "none"))
    out("")
    if ship:
        out("**The combined VitalAge (PhenoAge + daily steps) beats PhenoAge alone on held-out "
            "data, so it was shipped as `phenoage/combined.py` in commit 8e3c108. It is withdrawn: see section 4.** The gain is modest: "
            "%+.3f in C-index." % summary[primary][0])
    else:
        out("**The combined VitalAge does not clearly beat PhenoAge alone on held-out data "
            "(C-index change %+.3f, 95%% CI %+.3f to %+.3f), so no combined number is shipped.**"
            % (summary[primary][0], summary[primary][1][0], summary[primary][1][1]))
    out("")

    # ---- The single VitalAge: the validated model (age + PhenoAge acceleration +
    # log censored steps), refitted on all of 2005-06
    ab, ag, _ = fit_gompertz(st[["age"]].to_numpy(), s_t, s_d)
    cb, cg, _ = fit_gompertz(st[base_cols + ["log_steps_c"]].to_numpy(), s_t, s_d)
    icpt, slope = df.attrs["accel_fit"]
    # Same Gompertz-to-age mapping as PhenoAge. It is linear in the combined
    # linear predictor: VitalAge = (eta + K - a0) / a1
    K = np.log(np.expm1(cg * HORIZON) / cg) - np.log(np.expm1(ag * HORIZON) / ag)
    per_age_year = cb[1] / ab[1]
    per_accel_year = cb[2] / ab[1]
    per_doubling = cb[3] * np.log(2) / ab[1]
    ref_steps = float(st.steps_censored_per_day.median())
    vital = (cb[0] + cb[1] * st.age + cb[2] * st.pheno_accel + cb[3] * st.log_steps_c + K - ab[0]) / ab[1]
    c_vital, c_pheno = c_index(vital.to_numpy(), s_t, s_d), c_index(st.phenoage.to_numpy(), s_t, s_d)
    out("## The preliminary combined VitalAge model (withdrawn)")
    out("")
    out("Fitted on all %d people in 2005-06 with steps. It maps PhenoAge and censored hip steps "
        "to one age in years with Levine's method: the age whose 10-year mortality in an "
        "age-only Gompertz model equals the person's 10-year mortality in the combined model. "
        "Because that mapping is linear in the model's linear predictor, VitalAge splits "
        "exactly into years per input:" % len(st))
    out("")
    out("- PhenoAge enters as acceleration: PhenoAge minus (%.3f + %.3f x age), its trend "
        "on age in this sample, limited to %.1f to %+.1f years (1st and 99th percentiles);"
        % ((icpt, slope) + df.attrs["accel_clip"]))
    out("- each calendar year adds **%.3f years** of VitalAge, each year of PhenoAge "
        "acceleration adds **%.3f years**;" % (per_age_year, per_accel_year))
    out("- each doubling of daily steps changes VitalAge by **%+.2f years** at the same "
        "PhenoAge;" % per_doubling)
    out("- reference: median censored hip steps %.0f/day." % ref_steps)
    out("")
    out("In-sample C-index (optimistic): VitalAge %.3f, PhenoAge %.3f. Mean VitalAge %.1f vs "
        "mean age %.1f." % (c_vital, c_pheno, vital.mean(), st.age.mean()))
    out("")

    # ---- Mapping band values onto the NHANES scale
    band_offset = 1400.0
    lo_steps, hi_steps = 8000 - 5000, 8000 + 2300   # hip-equivalent of 8,000 band steps
    span = cb[3] * (np.log(hi_steps) - np.log(lo_steps)) / ab[1]
    out("## How band values map to the NHANES inputs")
    out("")
    out("- **Steps.** The model uses hip ActiGraph 7164 steps counted only in minutes with "
        ">= 500 counts (censored), because the 7164's raw step function counts many spurious "
        "steps during light movement (Tudor-Locke 2009: 9,676 raw vs 6,540 censored steps/day "
        "for US adults). Wrist bands count more steps than hip ActiGraphs: about +1,400 "
        "steps/day for wrist Fitbits vs a hip GT3X in free living, with 95%% limits of "
        "agreement of roughly -2,300 to +5,200 (Fitbit Charge 2 vs GT3X, PLoS One 2020; "
        "Fitbit Flex vs wGT3X: median +1,300, MAPE 15.5%%). VitalAge therefore converts band "
        "steps as `hip_steps = band_steps - %.0f` (never below 500). This chain is uncertain: "
        "the comparison studies used the newer GT3X and raw steps, not the 7164's censored "
        "steps, and band algorithms differ by brand. Across the limits of agreement, the "
        "hip-equivalent of 8,000 band steps ranges from about %d to %d, which moves VitalAge "
        "by about %.1f years." % (band_offset, lo_steps, hi_steps, abs(span)))
    out("- **MVPA minutes.** Hip counts >= 2020/min have no reliable equivalent in band "
        "\"active minutes\", which use heart rate or proprietary cadence rules, so MVPA is "
        "reported here for research but not used in VitalAge.")
    out("- **Counts per minute** have no band equivalent and are research-only.")
    out("")

    params = {
        "ship": bool(ship),
        "source": "NHANES 2005-2006, NCHS linked mortality through 2019; research/fit_model.py",
        "n": int(len(st)), "deaths": int(s_d.sum()),
        "age_model": {"b0": float(ab[0]), "b_age": float(ab[1]), "gamma": float(ag)},
        "combined_model": {"b0": float(cb[0]), "b_age": float(cb[1]), "b_pheno_accel": float(cb[2]),
                           "b_log_steps": float(cb[3]), "gamma": float(cg)},
        "accel_intercept": icpt, "accel_slope": slope,
        "accel_clip": list(df.attrs["accel_clip"]),
        "years_per_age_year": float(per_age_year),
        "years_per_accel_year": float(per_accel_year),
        "K": float(K),
        "years_per_doubling_steps": float(per_doubling),
        "reference_hip_steps": ref_steps,
        "band_to_hip_offset": band_offset,
        "heldout_c_change": float(summary[primary][0]),
        "heldout_c_change_ci": [float(x) for x in summary[primary][1]],
    }
    with open(os.path.join(DATA, "combined_params.json"), "w") as f:
        json.dump(params, f, indent=2)

    out("## Methods")
    out("")
    out("- **Sample:** NHANES 2003-2004 and 2005-2006 adults aged 20-84 with all 9 PhenoAge "
        "markers, eligible for mortality linkage, follow-up > 0 months. PhenoAge from "
        "`phenoage.core` with the published coefficients (Levine 2018).")
    out("- **Activity:** hip-worn ActiGraph 7164, 1-minute epochs, up to 7 days. Non-wear = "
        "runs of >= 60 zero-count minutes (Troiano et al. 2008, without their 2-minute "
        "allowance). Valid day >= 10 h wear; >= 4 valid days. Features: mean counts per wear "
        "minute, minutes/day >= 2020 counts/min (MVPA), and (2005-06) steps/day, raw and "
        "censored to minutes >= 500 counts (floored at 500 steps/day before taking logs).")
    out("- **Model:** Gompertz proportional hazards on months since exam, maximum likelihood. "
        "PhenoAge enters as age plus PhenoAge acceleration (residual of PhenoAge on age, "
        "winsorized at its 1st and 99th percentiles because a few very sick people have "
        "PhenoAges above 100), so activity is judged on what it adds beyond both.")
    out("- **Validation:** temporal split (fit 2003-04, test 2005-06) for counts and MVPA; "
        "5-fold cross-validation for steps; Harrell's C-index with %d paired bootstrap "
        "resamples for 95%% CIs." % N_BOOT)
    out("")
    out("## Limitations")
    out("")
    out("- Unweighted: estimates describe this sample, not the US population.")
    out("- One week of hip accelerometry at baseline; activity can change over 13-16 years "
        "of follow-up, and ill people move less (reverse causation), which inflates activity's "
        "apparent effect on early deaths.")
    out("- ActiGraph 7164 hip counts and its step function are not the same as a wrist band's "
        "step count; band steps typically run higher, so coefficients do not transfer "
        "one-to-one to consumer bands.")
    out("- US data from 2003-2006; not validated in Indian populations.")
    out("- The simplified non-wear rule may count some low-movement wear as non-wear.")

    with open(os.path.join(HERE, "RESULTS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
